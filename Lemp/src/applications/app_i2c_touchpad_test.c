void app_i2c_touchpad_test(void)
{
    fsp_err_t err;
    err = drv_i2c_touchpad_init();
    if (FSP_SUCCESS != err)
    {
        printf ("gt911 init failed, err=%d\r\n", (int) err);
        while (1)
        {
            R_BSP_SoftwareDelay (1000, BSP_DELAY_UNITS_MILLISECONDS);
        }
    }

    while (1)
    {
        i2c_touchpad_read();
        R_BSP_SoftwareDelay (10, BSP_DELAY_UNITS_MILLISECONDS);
    }
}

static fsp_err_t i2c_touchpad_read(void)
{
    fsp_err_t err;
    uint16_t x = 0, y = 0;

    err = touchpad_is_touched ();

    if (FSP_SUCCESS == err)
    {
        //循环读取每个触控点的位置值
        for (int i = 0; i < TOUCH_POINT_TOTAL; ++i)
        {
            touchpad_get_pos (&x, &y, i);
            printf ("No: %d, touched x: %d, touched y: %d\r\n", i, x, y);
        }
    }
    else if (FSP_ERR_INVALID_DATA != err)
    {
        return err;
    }

    return FSP_SUCCESS;

}

